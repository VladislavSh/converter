export const localeOf = lang => (lang === 'en' ? 'en-US' : 'ru-RU');

/** Returns the text for `key`, falling back to Russian and then to the key itself. */
export function translate(lang, key, vars) {
  const text = MESSAGES[lang]?.[key] ?? MESSAGES.ru[key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (placeholder, name) =>
    (Object.hasOwn(vars, name) ? String(vars[name]) : placeholder));
}
